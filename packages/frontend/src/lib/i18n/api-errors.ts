export function apiErrorMessage(tr: Translate, code: string, status: number): string {
  const key = messages[code] ?? (status === 403 ? 'api_error.permission' : status === 404 ? 'api_error.not_found' : status === 429 ? 'api_error.rate' : 'api_error.unknown');
  return tr(key);
}

export function apiErrorDetails(tr: Translate, details: unknown): Record<string, string[]> | undefined {
  if (!details || typeof details !== 'object' || Array.isArray(details)) return undefined;
  return Object.fromEntries(Object.entries(details).map(([field, value]) => [field,
    (Array.isArray(value) ? value : [value]).map(message =>
      translateFieldError(tr, String(message))),
  ]));
}

/** Translate known validation constraints without exposing server-language text. */
function translateFieldError(tr: Translate, message: string): string {
  if (/obligatori|required|requerid|vacío/i.test(message)) return tr('api_error.required');
  if (/decimales|decimal places/i.test(message)) return tr('api_error.decimals');
  const range = message.match(/entre ([-\d.,]+) y ([-\d.,]+)/i);
  if (range) return tr('api_error.range', { min: range[1]!, max: range[2]! });
  const max = message.match(/(?:exceder|máximo) ([-\d.,]+)/i);
  if (max) return tr(/caracteres/i.test(message) ? 'api_error.length' : 'api_error.maximum', { max: max[1]! });
  const min = message.match(/(?:menor a|al menos|mínimo) ([-\d.,]+)/i);
  if (min) return tr('api_error.minimum', { min: min[1]! });
  if (/no puede ser negativ/i.test(message)) return tr('api_error.nonnegative');
  return tr('api_error.field');
}
