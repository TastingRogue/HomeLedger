import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const banner = '// Generated by npm run locales:sync from locales/*.json. Do not edit.\n';
const json = value => JSON.stringify(value, null, 2);
const keys = value => Object.keys(value).sort();
const tokens = value => (value.match(/\{[^}]+\}/g) ?? []).sort();
const dictionaryExport = code => ({ es: 'es', en: 'en', 'pt-BR': 'ptBR' })[code] ?? 'dictionary';

function leaves(value, prefix = '') {
  if (typeof value === 'string') return { [prefix]: value };
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw Error(`Expected translated text at ${prefix}`);
  return Object.assign({}, ...Object.entries(value).map(([key, child]) => leaves(child, prefix ? `${prefix}.${key}` : key)));
}

export function validatePacks(packs, categories) {
  const canonical = packs.find(pack => pack.meta.code === 'en');
  if (!canonical) throw Error('English fallback pack is required');
  if (!packs.some(pack => pack.meta.code === 'es')) throw Error('Spanish key-type compatibility pack is required');
  const seen = new Set();
  const aliases = new Set();
  for (const pack of packs) {
    const meta = pack.meta;
    if (meta.draft) throw Error(`${meta.code}: finish translating the draft pack before registering it`);
    if (!/^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/.test(meta.code) || seen.has(meta.code)) throw Error(`Invalid or duplicate locale: ${meta.code}`);
    seen.add(meta.code);
    if (!meta.label?.trim() || !Number.isFinite(meta.order) || !Array.isArray(meta.aliases)) throw Error(`Invalid metadata: ${meta.code}`);
    if (!['', ' ', '\u00a0'].includes(meta.currencySpace)) throw Error(`Invalid currency spacing: ${meta.code}`);
    if (!Intl.DateTimeFormat.supportedLocalesOf([meta.intlTag]).length) throw Error(`Unsupported Intl locale: ${meta.intlTag}`);
    for (const alias of [meta.code, ...meta.aliases]) {
      const normalized = alias.trim().toLowerCase().replaceAll('_', '-');
      if (!/^[a-z]{2,3}(?:-[a-z0-9]{2,8})*$/.test(normalized) || aliases.has(normalized)) throw Error(`Duplicate or invalid locale alias: ${alias}`);
      aliases.add(normalized);
    }
    for (const section of ['ui', 'categories', 'receipts', 'desktop', 'themes']) {
      const expected = leaves(canonical[section]);
      const actual = leaves(pack[section]);
      if (json(keys(actual)) !== json(keys(expected))) throw Error(`${meta.code}.${section}: missing or extra translation keys`);
      for (const [key, value] of Object.entries(actual)) {
        if (!value.trim()) throw Error(`${meta.code}.${section}.${key}: empty translation`);
        if (json(tokens(value)) !== json(tokens(expected[key]))) throw Error(`${meta.code}.${section}.${key}: mismatched placeholders`);
      }
    }
  }
  if (json(categories.map(c => c.key).sort()) !== json(keys(canonical.categories))) throw Error('Default category keys do not match translations');
  if (new Set(categories.map(c => c.key)).size !== categories.length || categories.some(c => !['Ingreso','Gasto','Ambos'].includes(c.type))) throw Error('Invalid default category definitions');
}

// This resolver is emitted for both TypeScript and Electron CommonJS from the same source.
const resolver = `
function resolveLocale(value) {
  const normalized = String(value ?? '').trim().toLowerCase().replaceAll('_', '-');
  const exact = localeCodes.find(code => [code, ...localeMetadata[code].aliases].some(alias => alias.trim().toLowerCase().replaceAll('_', '-') === normalized));
  if (exact) return exact;
  const base = normalized.split('-')[0];
  return localeCodes.find(code => code === base) ?? 'en';
}
function isSupportedLocale(value) {
  return typeof value === 'string' && Object.hasOwn(localeMetadata, value);
}
`;

export function createArtifacts(packs, categories, haConfig) {
  validatePacks(packs, categories);
  if (!/DEFAULT_LOCALE: "list\([^)]+\)"/.test(haConfig)) throw Error('Home Assistant DEFAULT_LOCALE selector not found');
  packs = [...packs].sort((a,b) => a.meta.order - b.meta.order || a.meta.code.localeCompare(b.meta.code));
  const codes = packs.map(p => p.meta.code);
  const metadata = Object.fromEntries(packs.map(p => [p.meta.code, p.meta]));
  const backend = Object.fromEntries(packs.map(p => [p.meta.code, { categories:p.categories, receipts:p.receipts }]));
  const desktop = Object.fromEntries(packs.map(p => [p.meta.code, p.desktop]));
  const typedResolver = resolver.replace('function resolveLocale(value)', 'export function resolveLocale(value: unknown): LocaleCode')
    .replace('function isSupportedLocale(value)', 'export function isSupportedLocale(value: unknown): value is LocaleCode')
    .replace('[code, ...localeMetadata[code].aliases]', '([code, ...localeMetadata[code].aliases] as string[])');
  const artifacts = new Map();
  artifacts.set('packages/shared/src/locales.ts', banner + `export const localeMetadata = ${json(metadata)} as const;\nexport type LocaleCode = keyof typeof localeMetadata;\nexport const localeCodes = Object.keys(localeMetadata) as LocaleCode[];\nexport const backendTranslations = ${json(backend)} as const;\nexport const defaultCategories = ${json(categories)} as const;\n` + typedResolver);
  artifacts.set('packages/desktop/src/locale-data.cjs', banner + `const localeMetadata = ${json(metadata)};\nconst localeCodes = Object.keys(localeMetadata);\nconst dictionaries = ${json(desktop)};\n` + resolver + '\nmodule.exports = { localeMetadata, localeCodes, dictionaries, resolveLocale, isSupportedLocale };\n');
  for (const pack of packs) {
    const code = pack.meta.code;
    // Preserve existing imports while making the JSON pack the only editable source.
    const name = dictionaryExport(code);
    artifacts.set(`packages/frontend/src/lib/i18n/${code}.ts`, banner + `import { ui } from '../../../../../locales/${code}.json';\n` + (code === 'es' ? '' : "import type { TranslationKey } from './es';\n") + `export const ${name}${code === 'es' ? '' : ': Record<TranslationKey, string>'} = ui;\n` + (code === 'es' ? 'export type TranslationKey = keyof typeof es;\n' : ''));
  }
  const imports = packs.map(p => `import { ${dictionaryExport(p.meta.code)} as dictionary${codes.indexOf(p.meta.code)} } from './${p.meta.code}';`).join('\n');
  artifacts.set('packages/frontend/src/lib/i18n/generated.ts', banner + imports + '\nexport const locales = {\n' + packs.map((p,i) => `${JSON.stringify(p.meta.code)}: { ...${json(p.meta)}, dictionary: dictionary${i} },`).join('\n') + '\n};\n');
  const themes = Object.fromEntries(Object.keys(packs[0].themes).map(id => [id, Object.fromEntries(Object.keys(packs[0].themes[id]).map(field => [field,Object.fromEntries(packs.map(p => [p.meta.code,p.themes[id][field]]))]))]));
  artifacts.set('packages/frontend/src/lib/i18n/theme-texts.ts', banner + `export const themeTexts = ${json(themes)} as const;\n`);
  artifacts.set('ha-addon/config.yaml', haConfig.replace(/DEFAULT_LOCALE: "list\([^)]+\)"/, `DEFAULT_LOCALE: "list(${codes.join('|')})"`));
  return artifacts;
}

export function readPacks(directory) {
  return fs.readdirSync(directory).filter(name => name.endsWith('.json') && name !== 'categories.json').map(name => {
    const pack = JSON.parse(fs.readFileSync(path.join(directory,name),'utf8'));
    if (name !== `${pack.meta.code}.json`) throw Error(`Locale filename must match its code: ${name}`);
    return pack;
  });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const packs = readPacks(path.join(root,'locales'));
  const artifacts = createArtifacts(packs, JSON.parse(fs.readFileSync(path.join(root,'locales/categories.json'),'utf8')), fs.readFileSync(path.join(root,'ha-addon/config.yaml'),'utf8'));
  const stale = [];
  for (const [file, content] of artifacts) {
    const target = path.join(root,file);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(target) || fs.readFileSync(target,'utf8').replaceAll('\r\n','\n') !== content.replaceAll('\r\n','\n')) stale.push(file);
    } else fs.writeFileSync(target,content);
  }
  if (stale.length) throw Error(`Generated locale files are stale. Run npm run locales:sync:\n${stale.join('\n')}`);
  console.log(`${packs.length} language packs validated; ${artifacts.size} generated artifacts ${process.argv.includes('--check') ? 'verified' : 'updated'}.`);
}
